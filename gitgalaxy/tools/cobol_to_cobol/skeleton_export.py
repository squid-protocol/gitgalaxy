def load_confidence() -> dict[str, dict[str, Any]]:
    """Per ledger field, its field-testing record (the shipped fact_channel_confidence.json)."""
    text = resources.files("gitgalaxy.standards").joinpath("fact_channel_confidence.json").read_text(encoding="utf-8")
    return json.loads(text)["fields"]


def _plain(value: Any) -> Any:
    """JSON-ready: dataclasses (EngineScreenField rows inside a join) become dicts."""
    if is_dataclass(value) and not isinstance(value, type):
        return _plain(asdict(value))
    if isinstance(value, dict):
        return {str(k): _plain(v) for k, v in value.items()}
    if isinstance(value, (list, tuple, set)):
        items = [_plain(v) for v in value]
        return sorted(items, key=str) if isinstance(value, set) else items
    if isinstance(value, Path):
        return value.as_posix()
    return value


def _section(field: str, rows: Any, confidence: dict[str, dict[str, Any]]) -> dict[str, Any]:
    record = confidence.get(field, {})
    return {
        "ledger_field": field,
        "field_testing": record.get("status", "untested"),
        "tested_on_public": record.get("tested_on_public", 0),
        "tested_on_private": record.get("tested_on_private", 0),
        "facts": _plain(rows),
    }


def _names(row: dict[str, Any], path: str) -> bool:
    return any(row.get(key) == path for key in _PROGRAM_KEYS)


class SkeletonExporter:
    """Computes each join once, then slices it per program."""

    def __init__(self, ir: GalaxyIR, confidence: dict[str, dict[str, Any]] | None = None) -> None:
        self.ir = ir
        self.confidence = load_confidence() if confidence is None else confidence
        self._joins = {name: getattr(ir, method)() for name, (method, _) in PROGRAM_JOINS.items()}
        self._interfaces = ir.program_interfaces()

    def program(self, ef: EngineFile) -> dict[str, Any]:
        path = ef.file_path
        sections = {
            name: _section(field, getattr(ef, attr), self.confidence) for name, (attr, field) in FILE_CHANNELS.items()
        }
        for name, (_, field) in PROGRAM_JOINS.items():
            rows = [row for row in self._joins[name] if _names(row, path)]
            sections[name] = _section(field, rows, self.confidence)
        # #3615: the COMMAREA layout the program receives and the containers it reads / writes.
        # One mapping, not rows: `facts` is the program_interfaces() entry.
        interface = self._interfaces.get(path, {"commarea": None, "commarea_gap": None, "containers": []})
        sections["interface"] = _section(INTERFACE_FIELD, interface, self.confidence)
        return {
            "skeleton_version": SKELETON_VERSION,
            "source": {"db": self.ir.db_path.name, "repo": self.ir.repo_name, "commit": self.ir.commit_hash},
            "program": {
                "file": path,
                "language": ef.language,
                "program_ids": list(ef.program_ids),
                "total_loc": ef.total_loc,
                "copybooks": list(ef.copy_deps),
                "program_id_field_testing": self.confidence.get("program_id", {}).get("status", "untested"),
            },
            "sections": sections,
        }

    def estate(self) -> dict[str, Any]:
        sections = {
            name: _section(field, getattr(self.ir, name)(), self.confidence) for name, field in ESTATE_JOINS.items()
        }
        return {
            "skeleton_version": SKELETON_VERSION,
            "source": {"db": self.ir.db_path.name, "repo": self.ir.repo_name, "commit": self.ir.commit_hash},
            "inventory": self.ir.inventory(),
            "completeness": _plain(self.ir.completeness()),
            "api_surface": _plain(self.ir.api_surface()),
            "sections": sections,
        }


def write_skeletons(ir: GalaxyIR, program_keys: dict[str, str], out_dir: Path) -> int:
    """Writes <key>_skeleton.json for each program (repo-relative path -> output key) and
    estate.json; returns the number of program skeletons written."""
    out_dir.mkdir(parents=True, exist_ok=True)
    exporter = SkeletonExporter(ir)
    written = 0
    for rel, key in sorted(program_keys.items()):
        ef = ir.files.get(rel)
        if ef is None:
            continue
        (out_dir / f"{key}_skeleton.json").write_text(
            json.dumps(exporter.program(ef), indent=2, default=str), encoding="utf-8"
        )
        written += 1
    (out_dir / "estate.json").write_text(json.dumps(exporter.estate(), indent=2, default=str), encoding="utf-8")
    return written
