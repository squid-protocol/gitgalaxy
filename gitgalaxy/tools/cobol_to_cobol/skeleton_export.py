# ==============================================================================
# GitGalaxy Tool: verified skeleton export (#3614)
#
# PURPOSE:
# Hands what the engine extracted about each program -- its entry transactions,
# calls and their contracts, the CICS / DB2 / MQ / IMS / VSAM resources it
# touches, its screens, records, data moves, units of work and error handlers --
# to the code generators as one JSON file per program, so they build from the
# audited facts instead of re-deriving them from source.
#
#     06_skeleton/<key>_skeleton.json    one per refracted program
#     06_skeleton/estate.json            the estate-wide joins + completeness
#
# Every section names the ground-truth ledger field it comes from and carries
# that field's FIELD-TESTING record (gitgalaxy/standards/fact_channel_confidence.json,
# generated by tests/tools/field_testing.py): `field-tested`, `open` or
# `untested`, with the number of public and private estates it was tested on.
# A consumer reads `open` as "cross-verified on the keyed corpora, still finding
# defects on fresh estates": check it. The export states facts; it never fills
# a gap with a guess, and an empty section means the engine found nothing.
# ==============================================================================
