def test_both_sides_outcome_logs_fold_to_the_same_statements():
    cobol = db2.cobol_outcomes(
        "SELECT1 - SELECT 0 00000 0 0\n"  # a row
        "EXEC - UPDATE 0 00000 1 0\n"
        "COMMIT - COMMIT 0 00000 0 0\n"  # the program's own: not compared
        "SELECT1 - SELECT 100 02000 -1 0\n"  # no row
        "SELECT1 - SELECT -305 22002 0 0\n"  # a NULL with no indicator: Db2 returned the row
        "EXEC - DELETE 100 02000 0 0\n"
        "OPEN C1 SELECT 0 00000 0 0\nFETCH C1 SELECT 0 00000 0 0\nFETCH C1 SELECT 0 00000 0 0\n"
        "FETCH C1 SELECT 100 02000 0 0\nCLOSE C1 SELECT 0 00000 0 0\n"
        "EXEC - INSERT -803 23505 0 0\n"
    )
    java = db2.java_outcomes(
        "SELECT 0 00000 1 1 Q\nUPDATE 0 00000 1 0 U\nSELECT 0 00000 0 1 Q\nSELECT 0 00000 1 1 Q\n"
        "DELETE 0 00000 0 0 U\nSELECT 0 00000 2 1 Q\nINSERT -803 23505 0 0 U\n"
    )
    assert [(x["verb"], x["sqlcode"], x["sqlstate"], x["rows"]) for x in cobol] == [
        ("SELECT", 0, "00000", 1), ("UPDATE", 0, "00000", 1), ("SELECT", 100, "02000", 0),
        ("SELECT", 0, "00000", 1), ("DELETE", 100, "02000", 0), ("SELECT", 0, "00000", 2),
        ("INSERT", -803, "23505", None)]  # fmt: skip
    d = db2.compare_outcomes(cobol, java)
    assert d["equal"] == d["statements"] == 7 and not d["diffs"]


def test_a_differing_answer_is_named_field_by_field():
    cobol = db2.cobol_outcomes("SELECT1 - SELECT 100 02000 -1 0\nEXEC - INSERT -530 23503 0 0\n")
    java = db2.java_outcomes("SELECT 0 00000 1 1 Q\nINSERT 0 00000 1 0 U\nUPDATE 0 00000 1 0 U\n")
    d = db2.compare_outcomes(cobol, java)
    assert d["statements"] == 3 and d["equal"] == 0
    assert d["diffs"][0]["fields"] == [{"field": "sqlcode", "cobol": 100, "java": 0},
                                       {"field": "sqlstate", "cobol": "02000", "java": "00000"},
                                       {"field": "rows", "cobol": 0, "java": 1}]  # fmt: skip
    assert {f["field"] for f in d["diffs"][1]["fields"]} == {"sqlcode", "sqlstate"}
    assert d["diffs"][2]["missing"] == "cobol"


def test_a_table_dump_difference_is_named_by_column():
    head = "A|B|C\n"
    left = (head + "[1]|[x|y]|NULL\n[2]|[b]|[c]\n").encode()
    right = (head + "[1]|[x|y]|[0]\n[2]|[b]|[c]\n").encode()
    assert db2.split_row("[1]|[x|y]|NULL") == ["[1]", "[x|y]", "NULL"]
    d = db2.diff_dump(left, right)
    assert d["equal"] == 1 and d["diffs"] == [{"record": 1, "fields": [{"field": "C", "cobol": "NULL", "java": "[0]"}]}]


