def test_rows_reach_every_boundary_and_a_null_and_keys_stay_unique():
    tables = db2.parse_tables(CBSA)
    rows, pools = db2.generate_rows(_case(["IBMUSER.ACCOUNT"], rows=20), Path("."), tables)
    assert len(rows) == 20
    got = {c: [r[c] for _, r in rows] for c in rows[0][1]}
    rate = got["ACCOUNT_INTEREST_RATE"]
    for edge in (Decimal("9999.99"), Decimal("-9999.99"), Decimal("0.01"), Decimal("-0.01"), Decimal(0), None):
        assert edge in rate
    assert {2**31 - 1, -(2**31), 0, None} <= set(got["ACCOUNT_OVERDRAFT_LIMIT"])
    assert {"0001-01-01", "9999-12-31", "2024-02-29", None} <= set(got["ACCOUNT_OPENED"])
    assert {"ZZZZ", "", None} <= set(got["ACCOUNT_EYECATCHER"])  # full length, blank, NULL
    assert None not in got["ACCOUNT_SORTCODE"] and None not in got["ACCOUNT_NUMBER"]  # NOT NULL
    keys = [(r["ACCOUNT_SORTCODE"], r["ACCOUNT_NUMBER"]) for _, r in rows]
    assert len(set(keys)) == len(keys)
    assert sorted(pools["IBMUSER.ACCOUNT.ACCOUNT_NUMBER"]) == sorted(r["ACCOUNT_NUMBER"] for _, r in rows)
    again, _ = db2.generate_rows(_case(["IBMUSER.ACCOUNT"], rows=20), Path("."), tables)
    assert again == rows  # the seed decides


def test_a_case_steers_columns_and_keys_stay_unique_under_few_values():
    tables = db2.parse_tables(CBSA)
    case = _case([], tables={"IBMUSER.ACCOUNT": {"rows": 12, "columns": {
        "ACCOUNT_SORTCODE": {"values": ["987654", "123456"]}, "ACCOUNT_NUMBER": {"digits": True},
        "ACCOUNT_OPENED": {"null": False}}}})  # fmt: skip
    rows, _ = db2.generate_rows(case, Path("."), tables)
    assert {r["ACCOUNT_SORTCODE"] for _, r in rows} == {"987654", "123456"}
    assert all(r["ACCOUNT_NUMBER"].isdigit() and len(r["ACCOUNT_NUMBER"]) == 8 for _, r in rows)
    assert None not in [r["ACCOUNT_OPENED"] for _, r in rows]
    with pytest.raises(ValueError, match="no column"):
        db2.generate_rows(_case([], tables={"IBMUSER.ACCOUNT": {"columns": {"NOPE": {}}}}), Path("."), tables)


def test_foreign_keys_find_their_parent_and_identities_are_left_to_db2():
    tables = db2.parse_tables(GENAPP)
    rows, pools = db2.generate_rows(_case(["GENASA1.POLICY"], rows=6), Path("."), tables)
    order = [t for t, _ in rows]
    assert order.index("GENASA1.CUSTOMER") < order.index("GENASA1.POLICY")  # the parent first, added unasked
    assert all("CUSTOMERNUMBER" not in r for t, r in rows if t == "GENASA1.CUSTOMER")  # Db2's identity
    assert pools["GENASA1.CUSTOMER.CUSTOMERNUMBER"] == list(range(1000001, 1000007))
    assert pools["GENASA1.POLICY.POLICYNUMBER"] == [5, 7, 9, 11, 13, 15]  # START WITH 5, INCREMENT BY 2
    assert {r["CUSTOMERNUMBER"] for t, r in rows if t == "GENASA1.POLICY"} <= set(range(1000001, 1000007))
    seed = "".join(f"INSERT INTO {t} ({', '.join(r)}) VALUES ({', '.join(db2.literal(v) for v in r.values())});"
                   for t, r in rows)  # fmt: skip
    assert "INSERT INTO GENASA1.POLICY (CUSTOMERNUMBER, LASTCHANGED, COMMISSION)" in seed
    assert "'9999-12-31-23.59.59.999999'" in seed and "32767" in seed and "-32768" in seed
    rows2, _ = db2.generate_rows(_case(["CARDDEMO.TRANSACTION_TYPE_CATEGORY"], rows=10), Path("."),
                                 db2.parse_tables(CARDDEMO))  # fmt: skip
    parents = {r["TR_TYPE"] for t, r in rows2 if t == "CARDDEMO.TRANSACTION_TYPE"}
    kids = [r for t, r in rows2 if t == "CARDDEMO.TRANSACTION_TYPE_CATEGORY"]
    assert {r["TRC_TYPE_CODE"] for r in kids} <= parents
    assert len({(r["TRC_TYPE_CODE"], r["TRC_TYPE_CATEGORY"]) for r in kids}) == len(kids)
    assert {"", "Z" * 50, "B  "} <= {r["TR_DESCRIPTION"] for t, r in rows2 if t == "CARDDEMO.TRANSACTION_TYPE"}


