"""#4507: Db2 rows generated from the tables' declarations, and what Db2 answered each side.

Pinned without a corpus or a Db2, on DDL written like the estates' own (CBSA's CRETB01 + CREI101, GenApp's db2cre
with its identities and foreign keys, CardDemo's composite key, a DCLGEN's DECLARE TABLE): columns, NOT NULL and
keys are read; every boundary and a NULL reach the rows; keys stay unique and foreign keys find their parent; the
same seed makes the same rows; a scenario key `from` a table, with `miss`, is sometimes a key it does not hold. The
outcome logs of both sides (ggsql.c's, EquivalenceDb2Config's) fold to the same statements, and a difference in a
SQLCODE, a SQLSTATE, a row count or a table's column is named field by field.

The end-to-end proof (cbsa-updacc-generated) needs Docker, Db2 and a JDK: EQUIVALENCE_E2E=1.
"""

