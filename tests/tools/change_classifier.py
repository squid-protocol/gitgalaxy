#!/usr/bin/env python3
"""One change classifier for the PR workflows' plan jobs (#6278): map a changed path to an AREA, and say which test
code reads a docs / agent-config file.

    python tests/tools/change_classifier.py [FILE ...]          # print each file's area and readers
    python tests/tools/change_classifier.py --write             # regenerate tests/tools/docs_read_by_tests.txt
    python tests/tools/change_classifier.py --check             # exit 1 when the committed list is stale

Areas (area()): `agent-config` (.claude/**, CLAUDE.md), `test-read-doc` (a docs / Markdown file some test or tool opens),
`prose` (docs / Markdown nothing reads), `test-tooling` (tests/tools/**), `tests` (the rest of tests/), `engine`
(gitgalaxy/**), `workflow` (.github/**), `other`. An area says what a file IS; a consumer (ground_truth_plan.py first)
still decides what it reaches, because `prose` is only "prose" to the readers the list knows.

docs_read_by_tests.txt is GENERATED by scanning every .py under tests/, gitgalaxy/ and the repo root with `ast` for string
constants, f-string pieces and `a / "b" / "c"` path chains that name `docs/...`, `.claude/...` or a `*.md` file. Each line
is `ref<TAB>scope,scope`: a scope is the READER (`gitgalaxy`, `tests/<dir>`, or `tests/tools/<file>`), so a consumer can
ask "does a reader that my job runs open this path?". The scan over-approximates on purpose (a docstring-free string that
merely mentions a path counts; a dynamic path is cut to its literal directory prefix and covers everything under it): a
wrong answer can only run a job it did not need to, never skip one that reads a changed path. Stdlib only: plan jobs run
before anything is installed.
"""

from __future__ import annotations

import argparse
import ast
import fnmatch
import functools
import re
import subprocess
import sys
from collections.abc import Iterable
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
LIST_PATH = Path(__file__).resolve().with_name("docs_read_by_tests.txt")
SCAN_ROOTS = ("tests", "gitgalaxy")  # plus the *.py files straight under the repo root
# Files that hold path PATTERNS (planners and this classifier, with their tests), not readers: counting them would make
# every pattern they list a "read" by the tool every job runs. Their own changes are inputs to every consumer anyway.
PATTERN_HOLDERS = re.compile(r"(^|/)(test_)?(\w*_plan|change_classifier|merge_main)\.py$")  # merge_main: #6732
HEADER = (
    "# GENERATED by tests/tools/change_classifier.py --write (#6278): paths under docs/ and .claude/ and *.md files that\n"
    "# test or engine code names, with the scopes that name them. tests/tools/test_change_classifier.py fails when stale.\n"
)

# A path-looking run inside a string: rooted at docs / .claude, or any *.md name. `{` / `*` stay (f-string hole, glob).
_ROOTED = re.compile(r"(?<![\w./:])((?:\.\./)*(?:docs|\.claude)(?:/[\w.\-*{}]*)+)")
_MD = re.compile(r"(?<![\w.\-])((?:[\w.\-*{}]+/)*[\w\-*{}][\w.\-*{}]*\.md)\b")
_MARKERS = ("docs", ".claude", ".md")


def _text(path: Path) -> str:
    """UTF-8, else Latin-1 (never lossy; stdlib only, since plan jobs run before the package is installed)."""
    raw = path.read_bytes()
    try:
        return raw.decode("utf-8")
    except UnicodeDecodeError:
        return raw.decode("latin-1")


def scope_of(rel: str) -> str:
    """The reader a file stands for: tests/tools files singly, other tests per directory, the engine as one."""
    parts = rel.split("/")
    if parts[0] == "gitgalaxy":
        return "gitgalaxy"
    if parts[0] == "tests" and len(parts) > 2 and parts[1] == "tools":
        return "/".join(parts[:3])
    if parts[0] == "tests" and len(parts) > 2:
        return "/".join(parts[:2])
    return rel


def _clean(ref: str) -> str:
    """Strip a leading ./ or ../ and turn f-string holes into wildcards."""
    while ref.startswith(("./", "../")):
        ref = ref.split("/", 1)[1]
    ref = re.sub(r"\{[^}]*\}", "*", ref)  # an f-string hole is a wildcard
    return ref  # exact, or a glob (`*.md`, `docs/x/estate_*.json`): ref_matches() fnmatches it


def _refs_in(text: str) -> set[str]:
    out = set()
    for rx in (_ROOTED, _MD):
        for m in rx.finditer(text):
            ref = _clean(m.group(1))
            if ref and not ("*" in ref and "/" not in ref):  # `{name}.md` / `*.md`: no receiver to place it, so no ref
                out.add(ref)
    return out


_DOC_EXT = (".md", ".json", ".jsonl", ".txt", ".csv", ".svg", ".yml", ".yaml", ".toml", ".html")
_ROOTS = ("docs", ".claude")


def _leaf(node: ast.AST) -> str | None:
    """A literal string, `$NAME` for a variable, None for anything else."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.JoinedStr):  # f"estate_{kind}.json": the holes are wildcards
        return "".join(v.value if isinstance(v, ast.Constant) else "*" for v in node.values)
    return "$" + node.id if isinstance(node, ast.Name) else None


def _chain(node: ast.AST) -> list[str | None]:
    """`ROOT / "docs" / "a" / name` -> ["$ROOT", "docs", "a", "$name"]; a leaf is its string, `$var` or None."""
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Div):
        return [*_chain(node.left), *_chain(node.right)]
    return [_leaf(node)]


def _call_chain(node: ast.Call) -> list[str | None] | None:
    """os.path.join("docs", "x"), Path("docs", "x"), p.joinpath("x"): the literal arguments as a chain."""
    name = node.func.attr if isinstance(node.func, ast.Attribute) else getattr(node.func, "id", "")
    if name not in ("join", "joinpath", "Path", "PurePath"):
        return None
    head = [_leaf(node.func.value)] if isinstance(node.func, ast.Attribute) and name == "joinpath" else []
    return [*head, *(_leaf(a) for a in node.args)]


def _rooted_run(parts: list[str | None]) -> tuple[str, bool] | None:
    """The literal path from the first docs / .claude element to the next dynamic one: (path, ends_dynamic_or_dir)."""
    for i, p in enumerate(parts):
        if p is not None and not p.startswith("$") and p.split("/")[0] in _ROOTS:
            run = []
            for q in parts[i:]:
                if q is None or q.startswith("$"):
                    return "/".join(run), True
                run.append(q.strip("/"))
            return "/".join(run), False
    return None


def _chain_refs(parts: list[str | None], aliases: dict[str, str], known: set[str]) -> set[str]:
    out: set[str] = set()
    if parts and parts[0] is not None and parts[0].startswith("$") and parts[0][1:] in aliases:
        parts = [aliases[parts[0][1:]], *parts[1:]]
    run = _rooted_run(parts)
    if run:
        path, dynamic = run
        is_file = path.endswith(_DOC_EXT) and not dynamic
        out.add(path if is_file else path + "/")
    last = parts[-1] if parts else None
    if (
        len(parts) == 2
        and parts[0]
        and re.fullmatch(r"\$(?i:repo|root|repo_root|project_root|repo_dir|root_dir)", parts[0])
    ):
        if last and not last.startswith("$") and "/" not in last and not run:
            out.add("/" + last)  # ROOT / "CLAUDE.md": a file at the repository root
            return out
    if last and not last.startswith("$") and last.endswith(_DOC_EXT):
        if (last.endswith(".md") or last.rsplit("/", 1)[-1] in known) and not ("*" in last and "/" not in last):
            out.add(last)  # relative to a receiver we cannot see (an imported dir constant): the name stands for it
    return out


def _aliases(tree: ast.AST, defs: set[int] | None = None) -> dict[str, str]:
    """`DOCS = ROOT / "docs" / "language_status"`: later `DOCS / "x.json"` is docs/language_status/x.json."""
    aliases: dict[str, str] = {}
    for _ in range(2):  # an alias of an alias
        for node in ast.walk(tree):
            if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
                v = node.value
                parts = _chain(v) if isinstance(v, ast.BinOp) else (_call_chain(v) if isinstance(v, ast.Call) else None)
                if not parts:
                    continue
                if parts[0] is not None and parts[0].startswith("$") and parts[0][1:] in aliases:
                    parts = [aliases[parts[0][1:]], *parts[1:]]
                run = _rooted_run(parts)
                if run and not run[1]:
                    aliases[node.targets[0].id] = run[0]
                    if defs is not None:
                        defs.add(id(v))
    return aliases


def refs_of_source(src: str, known: set[str] | None = None) -> set[str]:
    """`known`: basenames of the files under docs/ and .claude/, so a bare `"x.json"` or `DIR / "x.json"` is a ref."""
    known = known or set()
    try:
        tree = ast.parse(src)
    except (SyntaxError, ValueError):
        return {"docs/", ".claude/"}  # cannot read it: assume it reads everything (the safe direction)
    defs: set[int] = set()  # the chains that only DEFINE an alias: the alias's uses are the reads
    aliases = _aliases(tree, defs)
    refs: set[str] = set()
    skip: set[int] = set()  # a docstring or bare string statement is not a read
    skip |= {id(n.value) for n in ast.walk(tree) if isinstance(n, ast.Expr) and isinstance(n.value, ast.Constant)}
    inner: set[int] = set()  # a chain is read once, from its outermost `/`
    heads: set[int] = (
        set()
    )  # alias names used as the head of a chain; any other use of an alias is the directory itself
    for node in ast.walk(tree):
        parts = None
        if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Div) and id(node) not in inner:
            inner |= {id(n) for n in ast.walk(node) if n is not node and isinstance(n, ast.BinOp)}
            parts = _chain(node)
            head = node
            while isinstance(head, ast.BinOp):
                head = head.left
            heads.add(id(head))
        elif isinstance(node, ast.Call):
            parts = _call_chain(node)
        if parts and id(node) not in defs:
            refs |= _chain_refs(parts, aliases, known)
        if isinstance(node, ast.Constant) and isinstance(node.value, str) and id(node) not in skip:
            refs |= _refs_in(node.value)
            if node.value.endswith(_DOC_EXT) and node.value in known:
                refs.add(node.value)
        elif isinstance(node, ast.JoinedStr):
            for v in node.values:
                if isinstance(v, ast.Constant) and isinstance(v.value, str):
                    refs |= _refs_in(v.value.lstrip("/"))  # `f"{root}/docs/x"`: the piece starts at the separator
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Name)
            and isinstance(node.ctx, ast.Load)
            and node.id in aliases
            and id(node) not in heads
        ):
            target = aliases[node.id]  # DOCS.glob(...), a call argument ...: the file, or the whole directory
            refs.add(target if target.endswith(_DOC_EXT) else target + "/")
    return refs


def _repo_files(root: Path, *paths: str) -> list[str] | None:
    """Repo-relative files under `paths` that git tracks, or that are new and not ignored; None without git. An ignored
    file an earlier test materialised (the evidence report's report.json) or a scratch file must not change a committed
    render (#6302)."""
    try:
        out = subprocess.run(
            ["git", "-C", str(root), "ls-files", "-z", "--cached", "--others", "--exclude-standard", "--", *paths],
            capture_output=True,
            check=True,
            timeout=60,
        ).stdout.decode("utf-8", "replace")
    except (OSError, subprocess.SubprocessError):
        return None
    return sorted({name for name in out.split("\0") if name})


def _py_files(root: Path, top: str | None = None, deep: bool = True) -> list[Path]:
    """The .py files under `top` (the repo root when None; only its direct children when not `deep`): git's view, else disk."""
    listed = _repo_files(root, "*.py" if top is None else top)
    if listed is not None:
        prefix = "" if top is None else top.rstrip("/") + "/"
        return [root / n for n in listed if n.endswith(".py") and (deep or "/" not in n[len(prefix) :])]
    base = root if top is None else root / top
    return [*(base.rglob("*.py") if deep else base.glob("*.py"))]


def _known_names(root: Path) -> set[str]:
    """Basenames of the files under docs/ and .claude/ that git knows. Without git, the files on disk."""
    listed = _repo_files(root, *_ROOTS)
    if listed is None:
        return {p.name for d in _ROOTS if (root / d).is_dir() for p in (root / d).rglob("*") if p.is_file()}
    return {name.rsplit("/", 1)[-1] for name in listed}


def scan(root: Path = REPO_ROOT) -> dict[str, list[str]]:
    """ref -> sorted reader scopes, over every .py under SCAN_ROOTS and the repo root."""
    files = _py_files(root, deep=False)
    for top in SCAN_ROOTS:
        files += _py_files(root, top)
    found: dict[str, set[str]] = {}
    known = _known_names(root)
    for f in sorted(files):
        rel = f.relative_to(root).as_posix()
        if "/." in "/" + rel or "__pycache__" in rel or PATTERN_HOLDERS.search(rel):
            continue
        try:
            src = _text(f)
        except OSError:
            continue
        is_test = f.name.startswith(("test_", "conftest"))
        for ref in refs_of_source(src, known):
            if is_test and ref in ("docs/", ".claude/"):
                continue  # a test builds its own docs/ tree under tmp_path; one that reads the real tree names a file
            found.setdefault(ref, set()).add(scope_of(rel))
    return {r: sorted(s) for r, s in sorted(found.items())}


def render(refs: dict[str, list[str]]) -> str:
    return HEADER + "".join(f"{r}\t{','.join(s)}\n" for r, s in refs.items())


def parse(text: str) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for ln in text.splitlines():
        if ln and not ln.startswith("#"):
            ref, _, scopes = ln.partition("\t")
            out[ref] = scopes.split(",")
    return out


def load(path: Path | None = None) -> dict[str, list[str]]:
    return parse((path or LIST_PATH).read_text(encoding="utf-8"))


def ref_matches(ref: str, path: str) -> bool:
    """Does a reader naming `ref` open `path`? A directory ref (trailing /, or a path below it), a suffix of the path
    (a relative or bare name), or a glob."""
    if ref.startswith("/"):
        return path == ref[1:]
    if "/" not in ref and not path.startswith(("docs/", ".claude/")):
        return (
            False  # a bare name is not placed: it can only be a file under docs/ or .claude/, never a root or code file
        )
    if ref.endswith("/"):
        return path.startswith(ref) or ("/" + ref) in "/" + path
    if "*" in ref:
        return fnmatch.fnmatch(path, ref) or fnmatch.fnmatch(path.rsplit("/", 1)[-1], ref)
    return path == ref or path.endswith("/" + ref) or path.startswith(ref + "/")


def readers_of(path: str, refs: dict[str, list[str]] | None = None) -> set[str]:
    """The scopes that name `path` (empty: nothing in tests/ or the engine opens it)."""
    refs = load() if refs is None else refs
    out: set[str] = set()
    for ref, scopes in refs.items():
        if ref_matches(ref, path):
            out.update(scopes)
    return out


# The scopes the Mainframe Ground Truth job runs: the engine, the tests it collects, and every tests/tools module those
# (and the ledger tool) name as a word, transitively. Over-approximate on purpose, like the scan.
GROUND_TRUTH_SEEDS = ("tests/tools/ground_truth_ledger.py", "tests/tools/mainframe_corpus.py")
GROUND_TRUTH_WORKFLOW = ".github/workflows/mainframe-ground-truth.yml"  # the tools its steps run, named by path
_GT_DIRS = ("gitgalaxy", "tests/cobol_mainframe", "tests/equivalence")


@functools.lru_cache(maxsize=4)
def ground_truth_scopes(root: Path = REPO_ROOT, workflow: bool = False) -> frozenset[str]:
    mods = {p.stem: p for p in _py_files(root, "tests/tools", deep=False)}
    word = re.compile(r"\w+")

    def named(p: Path) -> set[str]:
        if PATTERN_HOLDERS.search(p.as_posix()):
            return set()  # a planner lists the paths it skips: naming them is not running them
        try:
            return mods.keys() & set(word.findall(_text(p)))
        except OSError:
            return set()

    seen: set[str] = set()
    for p in [*_py_files(root, "tests/cobol_mainframe", deep=False), *(root / s for s in GROUND_TRUTH_SEEDS)]:
        seen |= named(p)
    todo = list(seen)
    while todo:
        for m in named(mods[todo.pop()]) - seen:
            seen.add(m)
            todo.append(m)
    if not workflow:
        return frozenset({*_GT_DIRS, *(f"tests/tools/{m}.py" for m in seen)})
    try:
        text = _text(root / GROUND_TRUTH_WORKFLOW)
    except OSError:
        text = ""
    todo = [m for m in re.findall(r"tests/tools/(\w+)\.(?:py|sh)", text) if m in mods and m not in seen]
    seen.update(todo)
    while todo:
        for m in named(mods[todo.pop()]) - seen:
            seen.add(m)
            todo.append(m)
    return frozenset({*_GT_DIRS, *(f"tests/tools/{m}.py" for m in seen)})


def runs_in_ground_truth(path: str, root: Path = REPO_ROOT) -> bool:
    """Is this `tests/tools/<name>.py` reachable from the job (named, transitively, by its tests, ledger tool or a tool
    its workflow runs: a wider net than the docs one, since a wrong "yes" only runs the job)? Anything unplaceable answers yes."""
    parts = path.split("/")
    if len(parts) != 3 or not path.endswith(".py") or parts[2].startswith(("test_", "conftest")):
        return True
    if PATTERN_HOLDERS.search(path):
        return True  # the planners stay inputs, as they were
    try:
        return path in ground_truth_scopes(root, workflow=True)
    except OSError:
        return True


def read_by_ground_truth(path: str, root: Path = REPO_ROOT) -> bool:
    """Does code the ground-truth job runs name this docs / Markdown / agent-config path? Any doubt (an unreadable list
    or tree) answers yes: the caller then runs the job."""
    try:
        return bool(readers_of(path, load()) & ground_truth_scopes(root))
    except (OSError, ValueError, KeyError):
        return True


# The Db2 area (#6278): what can move a Db2 equivalence proof. The det translator + runtime (det/, cobolrt), the forges
# beside them, the Db2 harness / oracle / image files, the det tools that run the proofs, and a Db2 case's own directory.
DB2_AREA = (
    "gitgalaxy/tools/cobol_to_java/*",
    "tests/tools/equivalence_db2.py",
    "tests/tools/db2_*.py",
    "tests/tools/det_port.py",
    "tests/tools/det_parity.py",
    "tests/tools/proof_sweep.py",
    "tests/tools/det_sweep_plan.py",
    "tests/equivalence/db2/*",
    "tests/equivalence/*db2*",
    "tests/equivalence/odbc_cli.pin",
    ".github/workflows/det-sweep.yml",
)


def db2_area(path: str, db2_cases: Iterable[str] = ()) -> bool:
    """Can a change to `path` move a Db2 proof? `db2_cases` names the Db2 equivalence cases (their directories count)."""
    if any(fnmatch.fnmatchcase(path, p) for p in DB2_AREA):
        return True
    parts = path.split("/")
    return len(parts) > 2 and parts[:2] == ["tests", "equivalence"] and parts[2] in set(db2_cases)


def area(path: str, refs: dict[str, list[str]] | None = None) -> str:
    if path.startswith(".claude/") or path == "CLAUDE.md":
        return "agent-config"
    docish = path.startswith("docs/") or path.endswith(".md")
    if docish and not path.startswith(("gitgalaxy/", "tests/")) and readers_of(path, refs):
        return "test-read-doc"
    if docish and not path.startswith(("gitgalaxy/", "tests/")):
        return "prose"
    if path.startswith("tests/tools/"):
        return "test-tooling"
    if path.startswith("tests/"):
        return "tests"
    if path.startswith("gitgalaxy/"):
        return "engine"
    if path.startswith(".github/"):
        return "workflow"
    return "other"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("files", nargs="*")
    ap.add_argument("--write", action="store_true", help="regenerate the committed list")
    ap.add_argument("--check", action="store_true", help="exit 1 when the committed list is stale")
    args = ap.parse_args()
    if args.write or args.check:
        fresh = render(scan())
        if args.write:
            LIST_PATH.write_text(fresh, encoding="utf-8")
            return 0
        stale = not LIST_PATH.exists() or LIST_PATH.read_text(encoding="utf-8") != fresh
        print("docs_read_by_tests.txt is stale: run change_classifier.py --write" if stale else "fresh")
        return int(stale)
    refs = load()
    for f in args.files:
        print(f"{area(f, refs):14} {f}  readers={sorted(readers_of(f, refs))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
