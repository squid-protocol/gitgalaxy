#!/usr/bin/env python3
"""Clean-scan scorer for the DOOM Port Speedrun harness (#5468).

Seven checks per port, on first-party code only (1-6 ported from the round-2 study's clean_check.py, #5457; 7 added
by #5874):
  1 coverage    every first-party source file is mapped (excluded ones listed with the engine's reason; a
                'Machine-Generated' exclusion is accepted when the head carries a generator banner)
  2 language    each mapped file's language fits its extension
  3 functions   function count within 3% of Universal Ctags (definitions only) OR of tree-sitter on the mapped
                files; the column functions_agree says which
  4 typosquat   no TYPOSQUATTING DETECTED log lines
  5 credentials no has_credentials files (SARIF error results are listed for review, never scored)
  6 health      rc=0 and no ERROR / CLASSIFICATION REFUTATION / Traceback log lines
  7 callgraph   C/C++ call edges match the tree-sitter body oracle (callgraph_oracle.py): no miss and no engine-only
                edge the callee's body never mentions. Constructor and function-pointer edges are reported, not
                scored, until the owner rules the edge convention; a port with no oracle is ``n/a`` (a pass, shown)

Second oracle: tree-sitter definition counts (``--oracle``), reported beside ctags, never scored: ctags misses
macro-defined functions (#5461), so "matches ctags" alone is not the claim. Third, on a subset: libclang (``--clang``,
doom_clang.py), which preprocesses first. Blind spots: see README.md.
"""

import collections
import json
import os
import re
import sqlite3
import subprocess
from pathlib import Path

SRC_EXT = {
    ".c", ".h", ".cc", ".cpp", ".cxx", ".c++", ".hpp", ".hh", ".hxx", ".inl", ".m", ".mm", ".rs", ".go", ".cs",
    ".java", ".js", ".mjs", ".ts", ".py", ".lua", ".asm", ".s", ".S", ".zig", ".ino", ".pas", ".kt", ".swift",
    ".f", ".f77", ".f90", ".f95", ".f03", ".f08", ".for", ".cr", ".fs", ".fsi", ".fsx", ".cbl", ".cob", ".cpy",
    ".cobol", ".dart", ".scm", ".ss", ".rkt", ".zs", ".rb",
}  # fmt: skip
# Hand-kept vendor names of the round-2 study. Off by default: the engine's own VendorDirectoryDetector decides
# (#4545, #5464). ``legacy_vendor=True`` adds them so round 2's table can be reproduced at its engine.
LEGACY_VENDOR_RE = re.compile(
    r"(^|/)(third[_-]?party|3rd[_-]?party|thirdparty|vendor(ed)?|external|extern|deps|contrib|libraries|"
    r"SDL2?([-_][\w.]*)?|SDL2_\w+[-\w.]*|zlib[-\w.]*|libpng[-\w.]*|lzma|bzip2|jpeg[-\w.]*|gdtoa|dumb|game-music-emu|"
    r"snes_spc|fmt|nlohmann|miniz|yyjson|spng|concurrentqueue|rnnoise|upnpnat|sqlite\d?|GeoIP|libxmp[-\w]*|"
    r"__MACOSX|glad|imgui|stb|tinyxml\w*|openal[-\w]*|freetype[-\w]*|libogg|libvorbis|\w+\.framework|node_modules)(/|$)",
    re.I,
)
GEN_BANNER = re.compile(
    r"generated by|do not edit|auto-?generated|automatically generated|this file was generated", re.I
)
# Files the engine rightly leaves out, scored as excluded-by-design (#5468 round 3): (category, why it is right)
BY_DESIGN_DIRS = {
    "docs": ("docs-tree", "documentation tree, not port source"),
    "doc": ("docs-tree", "documentation tree, not port source"),
    "__macosx": ("appledouble", "macOS AppleDouble resource-fork metadata"),
    "third_party": ("third-party", "engine-vendored third-party code"),
    "third-party": ("third-party", "engine-vendored third-party code"),
    "thirdparty": ("third-party", "engine-vendored third-party code"),
    "3rdparty": ("third-party", "engine-vendored third-party code"),
}
PARSER_GEN_BANNER = re.compile(r"generated (by|with) (re2c|bison|flex|lex|yacc|byacc|gperf|antlr)\b", re.I)
# Generator-output signatures that carry no "generated by" banner the engine or GEN_BANNER reads: Bison's "A Bison
# parser, made by" (re2c's parser.cc in gzdoom) and the "@generated" marker (room4doom info.rs).
GENERATED_SIGNATURE = re.compile(r"A Bison parser, made by|^\s*(//[/!]?|/\*|#)\s*@generated\b", re.I | re.M)
# Tooling directories the engine excludes by design (build scripts, a project web site), as path segment runs
TOOLING_DIRS = (
    (("build", "scripts"), "build-scripts directory, tooling not port source"),
    (("web", "site"), "project web-site directory, tooling not port source"),
)
EXPECT = {
    ".c": {"c"}, ".cc": {"cpp"}, ".cpp": {"cpp"}, ".cxx": {"cpp"}, ".c++": {"cpp"}, ".hpp": {"cpp"}, ".hh": {"cpp"},
    ".hxx": {"cpp"}, ".inl": {"cpp", "c"}, ".m": {"objective-c"}, ".mm": {"objective-c", "objective-cpp"},
    ".rs": {"rust"}, ".go": {"go"}, ".cs": {"csharp"}, ".java": {"java"}, ".js": {"javascript"},
    ".mjs": {"javascript"}, ".ts": {"typescript"}, ".py": {"python"}, ".lua": {"lua"}, ".zig": {"zig"},
    ".ino": {"cpp", "c", "arduino"}, ".kt": {"kotlin"}, ".swift": {"swift"}, ".pas": {"pascal"},
}  # fmt: skip
GUESS_LANG = {
    ".c": "c", ".h": "c", ".cpp": "cpp", ".cc": "cpp", ".hpp": "cpp", ".rs": "rust", ".go": "go",
    ".cs": "csharp", ".java": "java", ".js": "javascript", ".py": "python", ".m": "objective-c",
}  # fmt: skip
OBJC_SYNTAX = re.compile(r"^\s*(@interface|@implementation|@protocol|@class|@end|#import)\b", re.M)
CTAGS_LANG = {
    "c": "C", "cpp": "C++", "go": "Go", "java": "Java", "csharp": "C#", "rust": "Rust",
    "javascript": "JavaScript", "python": "Python", "objective-c": "ObjectiveC",
}  # fmt: skip
CTAGS_KINDS = {  # definitions, not prototypes or fields
    "C": {"function"}, "C++": {"function"}, "Go": {"func"}, "Java": {"method"}, "C#": {"method"},
    "Rust": {"function", "method"}, "JavaScript": {"function", "method"}, "Python": {"function", "member"},
    "ObjectiveC": {"method"},
}  # fmt: skip
# tree-sitter node types that are a function definition (a body), per engine language name
TS_FUNC_NODES = {
    "c": {"function_definition"}, "cpp": {"function_definition"}, "objective-c": {"function_definition", "method_definition"},
    "go": {"function_declaration", "method_declaration"}, "java": {"method_declaration", "constructor_declaration"},
    "csharp": {"method_declaration", "constructor_declaration"}, "rust": {"function_item"},
    "javascript": {"function_declaration", "method_definition"}, "python": {"function_definition"},
}  # fmt: skip
PAYLOAD = re.compile(
    r"Payload|Impossible Density|Minified|Line Length|Saturation|Monolithic|Lexical Monotony|Zero-Density", re.I
)
ENGINE_WIDE = re.compile(
    r"XGBoost|ML Threat|composition_repo|NOT a legitimate|dependency audit baseline|Unregistered rule"
)
FUNC_TOLERANCE = 0.03


def head(path, n=4096):
    try:
        with open(path, "rb") as fh:
            return fh.read(n).decode("utf-8", "replace")
    except OSError:
        return ""


def posix_rel(path, repo, sep=os.sep):
    """``path`` relative to ``repo`` with "/" separators: the scan DB keys and by_design_reason use "/", Windows gives "\\"."""
    return os.path.relpath(path, repo).replace(sep, "/")


def by_design_reason(rel, text):
    """(category, reason) when an unmapped file is excluded by design, else None.

    Categories: docs-tree, appledouble (``__MACOSX/`` or a ``._*`` file), third-party (a third_party / thirdparty
    directory the engine's vendor detector did not already cover), tooling-dir (``build/scripts``, ``web/site``),
    generated-parser (re2c / bison / flex output, recognised by its banner in ``text``, the head of the file),
    generated-signature (a Bison parser or ``@generated`` marker with no "generated by" banner).
    """
    parts = rel.split("/")
    for part in parts[:-1]:
        hit = BY_DESIGN_DIRS.get(part.lower())
        if hit:
            return hit
    if parts[-1].startswith("._"):
        return BY_DESIGN_DIRS["__macosx"]
    dirs = parts[:-1]
    for run, why in TOOLING_DIRS:
        if any(tuple(dirs[i : i + len(run)]) == run for i in range(len(dirs))):
            return "tooling-dir", why
    if PARSER_GEN_BANNER.search(text):
        return "generated-parser", "re2c/bison/flex-generated parser source"
    if GENERATED_SIGNATURE.search(text):
        return "generated-signature", "generator output recognised by content signature (Bison parser / @generated)"
    return None


def ctags_counts(repo, files_by_lang, scratch):
    """{relpath: definitions} from Universal Ctags, run per language on exactly the given files."""
    out = collections.Counter()
    for lang, files in files_by_lang.items():
        if lang not in CTAGS_LANG or not files:
            continue
        clang = CTAGS_LANG[lang]
        lst = Path(scratch) / ".ctags_list"
        lst.write_text("\n".join(files))
        r = subprocess.run(
            ["ctags", "--output-format=json", "--fields=+K", f"--languages={clang}", f"--language-force={clang}",
             "-L", str(lst), "-f", "-"],
            cwd=repo, capture_output=True, text=True, check=False,
        )  # fmt: skip
        for line in r.stdout.splitlines():
            try:
                tag = json.loads(line)
            except ValueError:
                continue
            if tag.get("_type") == "tag" and tag.get("kind") in CTAGS_KINDS[clang]:
                out[tag["path"]] += 1
    return out


def treesitter_counts(repo, files_by_lang):
    """{relpath: function definitions} from tree-sitter; empty when tree_sitter_language_pack is not installed."""
    try:
        import tree_sitter_language_pack
    except ImportError:
        return collections.Counter()
    out = collections.Counter()
    for lang, files in files_by_lang.items():
        kinds = TS_FUNC_NODES.get(lang)
        if not kinds:
            continue
        parser = tree_sitter_language_pack.get_parser("objc" if lang == "objective-c" else lang)
        for rel in files:
            try:
                data = (Path(repo) / rel).read_bytes()
            except OSError:
                continue
            stack = [parser.parse(data).root_node]
            while stack:
                node = stack.pop()
                if node.type in kinds:
                    out[rel] += 1
                stack.extend(node.children)
    return out


def language_misfits(mapped, repo, is_vendor):
    """[(path, language)] for mapped first-party files whose language does not fit the extension."""
    bad = []
    for p, (lang, _) in mapped.items():
        if is_vendor(p):
            continue
        ext = os.path.splitext(p)[1]
        lang = (lang or "").lower()
        if ext == ".h":
            if lang == "objective-c" and not OBJC_SYNTAX.search(head(Path(repo) / p, 65536)):
                bad.append((p, lang))
            elif lang not in {"c", "cpp", "objective-c"}:
                bad.append((p, lang))
        elif ext in EXPECT and lang not in EXPECT[ext]:
            bad.append((p, lang))
    return bad


def functions_ok(gg_total, ct_total):
    """Within tolerance of ctags; a ctags total of 0 (no parsable files) passes. Compares against the scaled bound."""
    return ct_total == 0 or abs(gg_total - ct_total) <= ct_total * FUNC_TOLERANCE


def functions_agreement(gg_total, ct_total, ts_total):
    """Which oracle the engine's function count is within tolerance of: 'ctags', 'tree-sitter', or '' (neither).

    ctags is tried first; tree-sitter counts only when it ran (``ts_total`` is None when it did not).
    """
    if functions_ok(gg_total, ct_total):
        return "ctags"
    if ts_total and functions_ok(gg_total, ts_total):
        return "tree-sitter"
    return ""


def verdict(fails, total=6):
    return "PERFECT" if not fails else f"{total - len(fails)}/{total}"


# Engine-only edge kinds (callgraph_oracle.body_oracle) that fail check 7: the callee appears nowhere in the caller's
# body, or only in a comment or string. ``type`` (a constructor), ``function-pointer`` and ``macro`` are unscored.
SCORED_ENGINE_ONLY = ("absent", "comment/string")
CALLGRAPH_NA = {
    k: "n/a"
    for k in (
        "callgraph_recall",
        "callgraph_precision",
        "callgraph_misses",
        "callgraph_engine_only",
        "callgraph_unscored",
    )
}


def callgraph_columns(oracle):
    """Check 7's row columns from a ``body_oracle`` result: misses, scored and unscored engine-only edge counts."""
    kinds = oracle["engine_only_by_kind"]
    return {
        "callgraph_recall": oracle["recall"],
        "callgraph_precision": oracle["precision"],
        "callgraph_misses": sum(oracle["misses_by_shape"].values()),
        "callgraph_engine_only": sum(kinds.get(k, 0) for k in SCORED_ENGINE_ONLY),
        "callgraph_unscored": sum(v for k, v in kinds.items() if k not in SCORED_ENGINE_ONLY),
    }


def callgraph_check(name, repo, dbp):
    """Check 7 for one scanned port: the C/C++ body oracle for a licensed C/C++ port, else the tree-sitter oracle
    over the port's go/java/csharp/rust/javascript/python/kotlin/lua/shell/tcl functions (ts_callgraph_oracle); ``n/a`` columns when the
    port has no function an oracle covers. Returns (columns, passed)."""
    import callgraph_oracle
    import ts_callgraph_oracle

    if name in callgraph_oracle.LICENSED:
        rows = callgraph_oracle.load_port(repo, dbp)
        oracle = callgraph_oracle.body_oracle(callgraph_oracle.Port(name, repo, rows)) if rows else None
    else:
        rows = ts_callgraph_oracle.load_port(repo, dbp)
        oracle = ts_callgraph_oracle.body_oracle(repo, rows) if rows else None
    if oracle is None:
        return dict(CALLGRAPH_NA), True
    cols = callgraph_columns(oracle)
    return cols, cols["callgraph_misses"] == 0 and cols["callgraph_engine_only"] == 0


def log_problems(log):
    """Health findings in a scan log: errors, refutations, tracebacks (engine-wide warnings and typosquat lines are not)."""
    return [
        ln[24:300]
        for ln in log.splitlines()
        if re.search(r"\[(ERROR|CRITICAL)\]|CLASSIFICATION REFUTATION|Traceback", ln)
        and not ENGINE_WIDE.search(ln)
        and "TYPOSQUATTING" not in ln
    ]


def _category_counts(by_design):
    """'docs-tree:12 appledouble:60' for the CSV reason column (empty when nothing was excluded by design)."""
    counts = collections.Counter(cat for _, cat, _ in by_design)
    return " ".join(f"{cat}:{n}" for cat, n in sorted(counts.items()))


def _engine_vendor_test(repo):
    from gitgalaxy.core.aperture import VendorDirectoryDetector

    detector = VendorDirectoryDetector(repo)

    def vendored(rel):
        parts = rel.split("/")[:-1]
        return any(detector.is_vendored("/".join(parts[: i + 1])) for i in range(len(parts)))

    return vendored


def _clang_oracle(row, det, repo, by_lang, nfunc):
    """libclang definition counts over the C/C++ files only (the engine's count is taken over the same files)."""
    import doom_clang

    c_files = [p for lang in ("c", "cpp") for p in by_lang.get(lang, [])]
    res = doom_clang.clang_counts(repo, c_files)
    if res is None:
        det["clang"] = "libclang not available"
        return
    counts, with_errors, from_db = res
    gg_c = sum(nfunc[p] for p in counts)
    cl_tot = sum(counts.values())
    row.update(
        clang_files=len(counts), clang_files_with_errors=with_errors, clang_compile_commands_files=from_db,
        clang_functions=cl_tot, clang_gg_functions=gg_c,
        clang_delta_pct=round(100 * (gg_c - cl_tot) / cl_tot, 1) if cl_tot else "",
    )  # fmt: skip
    det["clang_mismatch_worst"] = sorted(
        ((p, nfunc[p], n) for p, n in counts.items() if nfunc[p] != n), key=lambda t: -abs(t[1] - t[2])
    )[:12]


def score_port(name, repo, scan, scratch, oracle=False, legacy_vendor=False, clang=False):
    """Score one scanned port. Returns (row, details); ``row['verdict']`` is 'NO SCAN' when the scan DB is missing."""
    repo, scan = Path(repo), Path(scan)
    dbp = scan / f"{name}_galaxy_master.db"
    log_path, rc_path = scan / "scan.log", scan / "rc.txt"
    log = log_path.read_bytes().decode("utf-8", "replace") if log_path.exists() else ""
    rc = rc_path.read_text().strip() if rc_path.exists() else "?"
    row, det = {"variant": name, "rc": rc}, {}
    if not dbp.exists():
        row["verdict"] = "NO SCAN"
        return row, det
    con = sqlite3.connect(f"file:{dbp}?mode=ro", uri=True)
    mapped = {p: (lang, fid) for fid, p, lang in con.execute("select id, file_path, language from file_data")}
    excl = dict(con.execute("select file_path, exclusion_reason from excluded_artifacts"))
    nfunc = collections.Counter(
        dict(
            con.execute(
                "select d.file_path, count(*) from function_data f join file_data d on d.id=f.file_id group by d.file_path"
            )
        )
    )
    engine_vendored = _engine_vendor_test(repo)

    def is_vendor(rel):
        return bool(legacy_vendor and LEGACY_VENDOR_RE.search(rel)) or engine_vendored(rel)

    # 1 coverage
    missed, by_design, first_party = [], [], 0
    for root, dirs, files in os.walk(repo):
        dirs[:] = [d for d in dirs if d != ".git"]
        for fn in files:
            rel = posix_rel(os.path.join(root, fn), repo)
            if os.path.splitext(fn)[1] not in SRC_EXT or ".gitgalaxy/" in rel or is_vendor(rel):
                continue
            first_party += 1
            if rel in mapped or os.path.getsize(repo / rel) == 0:
                continue
            reason = excl.get(rel, "not mapped, no exclusion row")
            design = by_design_reason(rel, head(repo / rel))
            if design:
                by_design.append((rel, design[0], f"{design[1]} (engine: {reason})"))
                continue
            if "Machine-Generated" in reason and GEN_BANNER.search(head(repo / rel)):
                continue
            missed.append((rel, reason))
    data_only = []
    if missed:
        by_guess = collections.defaultdict(list)
        for rel, _ in missed:
            if os.path.splitext(rel)[1] in GUESS_LANG:
                by_guess[GUESS_LANG[os.path.splitext(rel)[1]]].append(rel)
        mc = ctags_counts(repo, by_guess, scratch)
        data_only = [(r, why) for r, why in missed if PAYLOAD.search(why) and mc[r] == 0]
        missed = [(r, why, mc[r]) for r, why in missed if (r, why) not in data_only]
    det["excluded_data_only"] = data_only
    vendor_leak = sorted(p for p in mapped if is_vendor(p) and os.path.splitext(p)[1] in SRC_EXT)
    row.update(
        first_party_src=first_party, missed_src=len(missed), excluded_by_design=len(by_design),
        excluded_by_design_reasons=_category_counts(by_design), data_files_excluded=len(data_only),
        vendor_files_mapped=len(vendor_leak),
    )  # fmt: skip
    det["missed"] = missed
    det["excluded_by_design"] = by_design
    det["vendor_leak_sample"] = vendor_leak[:15]

    # 2 language
    wrong_lang = language_misfits(mapped, repo, is_vendor)
    row["wrong_language"] = len(wrong_lang)
    det["wrong_language"] = wrong_lang

    # 3 functions vs ctags (first-party mapped files in ctags languages), tree-sitter beside it
    by_lang = collections.defaultdict(list)
    for p, (lang, _) in mapped.items():
        if not is_vendor(p) and (lang or "").lower() in CTAGS_LANG:
            by_lang[lang.lower()].append(p)
    ct = ctags_counts(repo, by_lang, scratch)
    files_ct = [p for ps in by_lang.values() for p in ps]
    gg_tot, ct_tot = sum(nfunc[p] for p in files_ct), sum(ct[p] for p in files_ct)
    diffs = sorted(((nfunc[p] - ct[p], p) for p in files_ct if nfunc[p] != ct[p]), key=lambda x: -abs(x[0]))
    row.update(
        gg_functions=gg_tot, ctags_functions=ct_tot,
        func_delta_pct=round(100 * (gg_tot - ct_tot) / ct_tot, 1) if ct_tot else "",
        files_func_mismatch=len(diffs), files_ctags_checked=len(files_ct),
    )  # fmt: skip
    det["func_mismatch_worst"] = [(p, nfunc[p], ct[p]) for _, p in diffs[:12]]
    ts_tot = None
    if oracle or not functions_ok(gg_tot, ct_tot):  # tree-sitter is the second oracle a ctags miss falls back to
        ts = treesitter_counts(repo, by_lang)
        ts_tot = sum(ts[p] for p in files_ct) if ts else None
    row["functions_agree"] = functions_agreement(gg_tot, ct_tot, ts_tot)
    if oracle:
        ts_tot = ts_tot or 0
        row["treesitter_functions"] = ts_tot if ts else ""
        row["ts_delta_pct"] = round(100 * (gg_tot - ts_tot) / ts_tot, 1) if ts_tot else ""
    if clang:
        _clang_oracle(row, det, repo, by_lang, nfunc)

    # 4 typosquat
    typos = re.findall(r"TYPOSQUATTING DETECTED: (.*)", log)
    row["typosquat"] = len(typos)
    det["typosquat"] = typos[:20]

    # 5 sarif + credentials
    sp = scan / f"{name}_galaxy_sarif.json"
    sarif = json.loads(sp.read_text())["runs"][0]["results"] if sp.exists() else []
    errs = collections.Counter(r.get("ruleId") for r in sarif if r.get("level") == "error")
    creds = [p for (p,) in con.execute("select file_path from file_data where has_credentials=1")]
    row.update(sarif_total=len(sarif), sarif_errors=sum(errs.values()), credential_files=len(creds))
    det["sarif_error_rules"] = errs.most_common()
    det["sarif_error_sample"] = [
        (
            r.get("ruleId"),
            r["locations"][0]["physicalLocation"]["artifactLocation"]["uri"],
            r["locations"][0]["physicalLocation"].get("region", {}).get("startLine"),
        )
        for r in sarif
        if r.get("level") == "error"
    ][:15]
    det["credential_files"] = creds
    con.close()

    # 7 callgraph (its numbers join the row below, in check order)
    cols7, ok7 = callgraph_check(name, repo, dbp)

    # 6 health
    bad = log_problems(log)
    row["log_problems"] = len(bad)
    det["log_problems"] = bad[:15]

    row.update(cols7)
    checks = [
        ("coverage", not missed), ("language", not wrong_lang), ("functions", bool(row["functions_agree"])),
        ("typosquat", not typos), ("credentials", not creds), ("health", rc == "0" and not bad),
        ("callgraph", ok7),
    ]  # fmt: skip
    fails = [k for k, ok in checks if not ok]
    row["fails"] = " ".join(fails)
    row["verdict"] = verdict(fails, 7)
    row["verdict6"] = verdict([k for k in fails if k != "callgraph"])
    return row, det
