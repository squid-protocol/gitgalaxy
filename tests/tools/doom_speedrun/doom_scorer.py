#!/usr/bin/env python3
"""Clean-scan scorer for the DOOM Port Speedrun harness (#5468).

Six checks per port, on first-party code only (ported from the round-2 study's clean_check.py, #5457):
  1 coverage    every first-party source file is mapped (excluded ones listed with the engine's reason; a
                'Machine-Generated' exclusion is accepted when the head carries a generator banner)
  2 language    each mapped file's language fits its extension
  3 functions   function count within 3% of Universal Ctags (definitions only) on the mapped files ctags can parse
  4 typosquat   no TYPOSQUATTING DETECTED log lines
  5 credentials no has_credentials files (SARIF error results are listed for review, never scored)
  6 health      rc=0 and no ERROR / CLASSIFICATION REFUTATION / Traceback log lines

Second oracle: tree-sitter definition counts (``--oracle``), reported beside ctags, never scored: ctags misses
macro-defined functions (#5461), so "matches ctags" alone is not the claim. Blind spots: see README.md.
"""

import collections
import json
import os
import re
import sqlite3
import subprocess
from pathlib import Path

SRC_EXT = {
    ".c", ".h", ".cc", ".cpp", ".cxx", ".c++", ".hpp", ".hh", ".hxx", ".inl", ".m", ".mm", ".rs", ".go", ".cs",
    ".java", ".js", ".mjs", ".ts", ".py", ".lua", ".asm", ".s", ".S", ".zig", ".ino", ".pas", ".kt", ".swift",
}  # fmt: skip
# Hand-kept vendor names of the round-2 study. Off by default: the engine's own VendorDirectoryDetector decides
# (#4545, #5464). ``legacy_vendor=True`` adds them so round 2's table can be reproduced at its engine.
LEGACY_VENDOR_RE = re.compile(
    r"(^|/)(third[_-]?party|3rd[_-]?party|thirdparty|vendor(ed)?|external|extern|deps|contrib|libraries|"
    r"SDL2?([-_][\w.]*)?|SDL2_\w+[-\w.]*|zlib[-\w.]*|libpng[-\w.]*|lzma|bzip2|jpeg[-\w.]*|gdtoa|dumb|game-music-emu|"
    r"snes_spc|fmt|nlohmann|miniz|yyjson|spng|concurrentqueue|rnnoise|upnpnat|sqlite\d?|GeoIP|libxmp[-\w]*|"
    r"__MACOSX|glad|imgui|stb|tinyxml\w*|openal[-\w]*|freetype[-\w]*|libogg|libvorbis|\w+\.framework|node_modules)(/|$)",
    re.I,
)
GEN_BANNER = re.compile(
    r"generated by|do not edit|auto-?generated|automatically generated|this file was generated", re.I
)
EXPECT = {
    ".c": {"c"}, ".cc": {"cpp"}, ".cpp": {"cpp"}, ".cxx": {"cpp"}, ".c++": {"cpp"}, ".hpp": {"cpp"}, ".hh": {"cpp"},
    ".hxx": {"cpp"}, ".inl": {"cpp", "c"}, ".m": {"objective-c"}, ".mm": {"objective-c", "objective-cpp"},
    ".rs": {"rust"}, ".go": {"go"}, ".cs": {"csharp"}, ".java": {"java"}, ".js": {"javascript"},
    ".mjs": {"javascript"}, ".ts": {"typescript"}, ".py": {"python"}, ".lua": {"lua"}, ".zig": {"zig"},
    ".ino": {"cpp", "c", "arduino"}, ".kt": {"kotlin"}, ".swift": {"swift"}, ".pas": {"pascal"},
}  # fmt: skip
GUESS_LANG = {
    ".c": "c", ".h": "c", ".cpp": "cpp", ".cc": "cpp", ".hpp": "cpp", ".rs": "rust", ".go": "go",
    ".cs": "csharp", ".java": "java", ".js": "javascript", ".py": "python", ".m": "objective-c",
}  # fmt: skip
OBJC_SYNTAX = re.compile(r"^\s*(@interface|@implementation|@protocol|@class|@end|#import)\b", re.M)
CTAGS_LANG = {
    "c": "C", "cpp": "C++", "go": "Go", "java": "Java", "csharp": "C#", "rust": "Rust",
    "javascript": "JavaScript", "python": "Python", "objective-c": "ObjectiveC",
}  # fmt: skip
CTAGS_KINDS = {  # definitions, not prototypes or fields
    "C": {"function"}, "C++": {"function"}, "Go": {"func"}, "Java": {"method"}, "C#": {"method"},
    "Rust": {"function", "method"}, "JavaScript": {"function", "method"}, "Python": {"function", "member"},
    "ObjectiveC": {"method"},
}  # fmt: skip
# tree-sitter node types that are a function definition (a body), per engine language name
TS_FUNC_NODES = {
    "c": {"function_definition"}, "cpp": {"function_definition"}, "objective-c": {"function_definition", "method_definition"},
    "go": {"function_declaration", "method_declaration"}, "java": {"method_declaration", "constructor_declaration"},
    "csharp": {"method_declaration", "constructor_declaration"}, "rust": {"function_item"},
    "javascript": {"function_declaration", "method_definition"}, "python": {"function_definition"},
}  # fmt: skip
PAYLOAD = re.compile(
    r"Payload|Impossible Density|Minified|Line Length|Saturation|Monolithic|Lexical Monotony|Zero-Density", re.I
)
ENGINE_WIDE = re.compile(
    r"XGBoost|ML Threat|composition_repo|NOT a legitimate|dependency audit baseline|Unregistered rule"
)
FUNC_TOLERANCE = 0.03


def head(path, n=4096):
    try:
        with open(path, "rb") as fh:
            return fh.read(n).decode("utf-8", "replace")
    except OSError:
        return ""


def ctags_counts(repo, files_by_lang, scratch):
    """{relpath: definitions} from Universal Ctags, run per language on exactly the given files."""
    out = collections.Counter()
    for lang, files in files_by_lang.items():
        if lang not in CTAGS_LANG or not files:
            continue
        clang = CTAGS_LANG[lang]
        lst = Path(scratch) / ".ctags_list"
        lst.write_text("\n".join(files))
        r = subprocess.run(
            ["ctags", "--output-format=json", "--fields=+K", f"--languages={clang}", f"--language-force={clang}",
             "-L", str(lst), "-f", "-"],
            cwd=repo, capture_output=True, text=True, check=False,
        )  # fmt: skip
        for line in r.stdout.splitlines():
            try:
                tag = json.loads(line)
            except ValueError:
                continue
            if tag.get("_type") == "tag" and tag.get("kind") in CTAGS_KINDS[clang]:
                out[tag["path"]] += 1
    return out


def treesitter_counts(repo, files_by_lang):
    """{relpath: function definitions} from tree-sitter; {} when tree_sitter_language_pack is not installed."""
    try:
        import tree_sitter_language_pack
    except ImportError:
        return {}
    out = collections.Counter()
    for lang, files in files_by_lang.items():
        kinds = TS_FUNC_NODES.get(lang)
        if not kinds:
            continue
        parser = tree_sitter_language_pack.get_parser("objc" if lang == "objective-c" else lang)
        for rel in files:
            try:
                data = (Path(repo) / rel).read_bytes()
            except OSError:
                continue
            stack = [parser.parse(data).root_node]
            while stack:
                node = stack.pop()
                if node.type in kinds:
                    out[rel] += 1
                stack.extend(node.children)
    return out


def language_misfits(mapped, repo, is_vendor):
    """[(path, language)] for mapped first-party files whose language does not fit the extension."""
    bad = []
    for p, (lang, _) in mapped.items():
        if is_vendor(p):
            continue
        ext = os.path.splitext(p)[1]
        lang = (lang or "").lower()
        if ext == ".h":
            if lang == "objective-c" and not OBJC_SYNTAX.search(head(Path(repo) / p, 65536)):
                bad.append((p, lang))
            elif lang not in {"c", "cpp", "objective-c"}:
                bad.append((p, lang))
        elif ext in EXPECT and lang not in EXPECT[ext]:
            bad.append((p, lang))
    return bad


def functions_ok(gg_total, ct_total):
    """Within tolerance of ctags; a ctags total of 0 (no parsable files) passes. Compares against the scaled bound."""
    return ct_total == 0 or abs(gg_total - ct_total) <= ct_total * FUNC_TOLERANCE


def verdict(fails):
    return "PERFECT" if not fails else f"{6 - len(fails)}/6"


def log_problems(log):
    """Health findings in a scan log: errors, refutations, tracebacks (engine-wide warnings and typosquat lines are not)."""
    return [
        ln[24:300]
        for ln in log.splitlines()
        if re.search(r"\[(ERROR|CRITICAL)\]|CLASSIFICATION REFUTATION|Traceback", ln)
        and not ENGINE_WIDE.search(ln)
        and "TYPOSQUATTING" not in ln
    ]


def _engine_vendor_test(repo):
    from gitgalaxy.core.aperture import VendorDirectoryDetector

    detector = VendorDirectoryDetector(repo)

    def vendored(rel):
        parts = rel.split("/")[:-1]
        return any(detector.is_vendored("/".join(parts[: i + 1])) for i in range(len(parts)))

    return vendored


def score_port(name, repo, scan, scratch, oracle=False, legacy_vendor=False):
    """Score one scanned port. Returns (row, details); ``row['verdict']`` is 'NO SCAN' when the scan DB is missing."""
    repo, scan = Path(repo), Path(scan)
    dbp = scan / f"{name}_galaxy_master.db"
    log_path, rc_path = scan / "scan.log", scan / "rc.txt"
    log = log_path.read_bytes().decode("utf-8", "replace") if log_path.exists() else ""
    rc = rc_path.read_text().strip() if rc_path.exists() else "?"
    row, det = {"variant": name, "rc": rc}, {}
    if not dbp.exists():
        row["verdict"] = "NO SCAN"
        return row, det
    con = sqlite3.connect(f"file:{dbp}?mode=ro", uri=True)
    mapped = {p: (lang, fid) for fid, p, lang in con.execute("select id, file_path, language from file_data")}
    excl = dict(con.execute("select file_path, exclusion_reason from excluded_artifacts"))
    nfunc = collections.Counter(
        dict(
            con.execute(
                "select d.file_path, count(*) from function_data f join file_data d on d.id=f.file_id group by d.file_path"
            )
        )
    )
    engine_vendored = _engine_vendor_test(repo)

    def is_vendor(rel):
        return bool(legacy_vendor and LEGACY_VENDOR_RE.search(rel)) or engine_vendored(rel)

    # 1 coverage
    missed, first_party = [], 0
    for root, dirs, files in os.walk(repo):
        dirs[:] = [d for d in dirs if d != ".git"]
        for fn in files:
            rel = os.path.relpath(os.path.join(root, fn), repo)
            if os.path.splitext(fn)[1] not in SRC_EXT or ".gitgalaxy/" in rel or is_vendor(rel):
                continue
            first_party += 1
            if rel in mapped or os.path.getsize(repo / rel) == 0:
                continue
            reason = excl.get(rel, "not mapped, no exclusion row")
            if "Machine-Generated" in reason and GEN_BANNER.search(head(repo / rel)):
                continue
            missed.append((rel, reason))
    data_only = []
    if missed:
        by_guess = collections.defaultdict(list)
        for rel, _ in missed:
            if os.path.splitext(rel)[1] in GUESS_LANG:
                by_guess[GUESS_LANG[os.path.splitext(rel)[1]]].append(rel)
        mc = ctags_counts(repo, by_guess, scratch)
        data_only = [(r, why) for r, why in missed if PAYLOAD.search(why) and mc[r] == 0]
        missed = [(r, why, mc[r]) for r, why in missed if (r, why) not in data_only]
    det["excluded_data_only"] = data_only
    vendor_leak = sorted(p for p in mapped if is_vendor(p) and os.path.splitext(p)[1] in SRC_EXT)
    row.update(
        first_party_src=first_party, missed_src=len(missed), data_files_excluded=len(data_only),
        vendor_files_mapped=len(vendor_leak),
    )  # fmt: skip
    det["missed"] = missed
    det["vendor_leak_sample"] = vendor_leak[:15]

    # 2 language
    wrong_lang = language_misfits(mapped, repo, is_vendor)
    row["wrong_language"] = len(wrong_lang)
    det["wrong_language"] = wrong_lang

    # 3 functions vs ctags (first-party mapped files in ctags languages), tree-sitter beside it
    by_lang = collections.defaultdict(list)
    for p, (lang, _) in mapped.items():
        if not is_vendor(p) and (lang or "").lower() in CTAGS_LANG:
            by_lang[lang.lower()].append(p)
    ct = ctags_counts(repo, by_lang, scratch)
    files_ct = [p for ps in by_lang.values() for p in ps]
    gg_tot, ct_tot = sum(nfunc[p] for p in files_ct), sum(ct[p] for p in files_ct)
    diffs = sorted(((nfunc[p] - ct[p], p) for p in files_ct if nfunc[p] != ct[p]), key=lambda x: -abs(x[0]))
    row.update(
        gg_functions=gg_tot, ctags_functions=ct_tot,
        func_delta_pct=round(100 * (gg_tot - ct_tot) / ct_tot, 1) if ct_tot else "",
        files_func_mismatch=len(diffs), files_ctags_checked=len(files_ct),
    )  # fmt: skip
    det["func_mismatch_worst"] = [(p, nfunc[p], ct[p]) for _, p in diffs[:12]]
    if oracle:
        ts = treesitter_counts(repo, by_lang)
        ts_tot = sum(ts[p] for p in files_ct)
        row["treesitter_functions"] = ts_tot if ts else ""
        row["ts_delta_pct"] = round(100 * (gg_tot - ts_tot) / ts_tot, 1) if ts_tot else ""

    # 4 typosquat
    typos = re.findall(r"TYPOSQUATTING DETECTED: (.*)", log)
    row["typosquat"] = len(typos)
    det["typosquat"] = typos[:20]

    # 5 sarif + credentials
    sp = scan / f"{name}_galaxy_sarif.json"
    sarif = json.loads(sp.read_text())["runs"][0]["results"] if sp.exists() else []
    errs = collections.Counter(r.get("ruleId") for r in sarif if r.get("level") == "error")
    creds = [p for (p,) in con.execute("select file_path from file_data where has_credentials=1")]
    row.update(sarif_total=len(sarif), sarif_errors=sum(errs.values()), credential_files=len(creds))
    det["sarif_error_rules"] = errs.most_common()
    det["sarif_error_sample"] = [
        (
            r.get("ruleId"),
            r["locations"][0]["physicalLocation"]["artifactLocation"]["uri"],
            r["locations"][0]["physicalLocation"].get("region", {}).get("startLine"),
        )
        for r in sarif
        if r.get("level") == "error"
    ][:15]
    det["credential_files"] = creds
    con.close()

    # 6 health
    bad = log_problems(log)
    row["log_problems"] = len(bad)
    det["log_problems"] = bad[:15]

    checks = [
        ("coverage", not missed), ("language", not wrong_lang), ("functions", functions_ok(gg_tot, ct_tot)),
        ("typosquat", not typos), ("credentials", not creds), ("health", rc == "0" and not bad),
    ]  # fmt: skip
    fails = [k for k, ok in checks if not ok]
    row["fails"] = " ".join(fails)
    row["verdict"] = verdict(fails)
    return row, det
