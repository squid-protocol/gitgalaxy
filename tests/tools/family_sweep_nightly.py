#!/usr/bin/env python3
"""The nightly family-validity re-measure (#8863): sweep the pinned language-crucible and keep ONE draft PR with the new baseline.

    python tests/tools/family_sweep_nightly.py [--dry-run] [--force] [--root DIR]

Run by a systemd user timer in a dedicated worktree of origin/main (docs/agents/family-validity-checklist.md, "Nightly"). One run:

  1. gate: box_status.py must say GREEN (else it exits 0, "skipped"); `--force` ignores the verdict and the stamp;
  2. once per main SHA per UTC day: a done-stamp under <scratch>/family-sweep-nightly/;
  3. its OWN checkout of the pinned language-crucible (never the shared one: `crucible_pins.py sync` moves a shared checkout under
     other jobs' feet), synced to tests/crucible_pins.toml;
  4. `family_oracle_sweep.py --write` under tests/tools/box/heavy-run.sh, with this worktree first on PYTHONPATH (a venv's editable
     install points at another checkout and would scan the wrong engine), then `family_validity_chart.py`;
  5. when the baseline or the grid changed: branch `bot/family-validity-baseline`, one commit, `--force-with-lease`, and a single
     standing DRAFT PR whose body lists regressions first, then improvements, the red-cell count, and the per-language epic lines
     (`family_red_cells.py --slices`). The PR is refreshed in place each night, never duplicated; nothing is merged.

When nothing changed it publishes nothing. It measures and reports: it never edits an engine rule.
"""

from __future__ import annotations

import argparse
import datetime
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
REPO = TOOLS.parents[1]
sys.path.insert(0, str(TOOLS))
import census_nightly  # noqa: E402  (box_verdict: one gate for every nightly)
import equivalence_env  # noqa: E402  (scratch_root: the shared scratch every nightly uses)
import family_red_cells  # noqa: E402

GH = shutil.which("gh") or "gh"
BRANCH = "bot/family-validity-baseline"
BASELINE = "tests/family_validity_baseline.json"
CHART_FILES = ("docs/self_scan/family_validity_chart.svg", "docs/self_scan/family_validity_matrix.svg")
FELL = 0.05  # a cell whose weaker score dropped by more than this is a regression, listed first


def weakest(cell: dict) -> float | None:
    vals = [v for v in (cell.get("recall"), cell.get("precision")) if v is not None]
    return min(vals) if vals else None


def diff_cells(old: dict, new: dict) -> dict[str, list[str]]:
    """{'regressed': [...], 'improved': [...], 'new': [...]} comparing two baselines' weaker-of-recall-and-precision per cell."""
    out: dict[str, list[str]] = {"regressed": [], "improved": [], "new": []}
    for lang, fams in new.get("cells", {}).items():
        for fam, cell in fams.items():
            before = old.get("cells", {}).get(lang, {}).get(fam)
            if before is None:
                out["new"].append(f"{lang} {fam}")
                continue
            a, b = weakest(before), weakest(cell)
            a = 0.0 if a is None else a
            b = 0.0 if b is None else b
            if b < a - FELL:
                out["regressed"].append(f"{lang} {fam}: {a:.2f} -> {b:.2f}")
            elif b > a + FELL:
                out["improved"].append(f"{lang} {fam}: {a:.2f} -> {b:.2f}")
    return out


def pr_body(sha: str, before: int, after: int, changes: dict[str, list[str]], slices: list[str]) -> str:
    def block(title: str, rows: list[str], limit: int = 40) -> str:
        if not rows:
            return ""
        shown = "\n".join(f"- {r}" for r in rows[:limit])
        more = f"\n- ... and {len(rows) - limit} more" if len(rows) > limit else ""
        return f"\n### {title} ({len(rows)})\n{shown}{more}\n"

    return (
        f"Nightly re-measure of the keyword-family validity grid on the pinned language-crucible, engine `{sha[:12]}` (Part of #8863).\n\n"
        f"Red cells (weaker of recall and precision under 0.8, at least 10 oracle functions): **{before} -> {after}**.\n"
        + block("Regressions: open these first", changes["regressed"])
        + block("Improvements", changes["improved"])
        + block("New cells", changes["new"])
        + "\n### Epic lines for #8863 (`family_red_cells.py --slices`)\n"
        + "\n".join(slices)
        + "\n\nGenerated by `tests/tools/family_sweep_nightly.py`; refreshed in place each night. Merge it to publish the new grid; do not edit it by hand."
    )


def stamp_file(root: Path, sha: str) -> Path:
    return root / "family-sweep-nightly" / f"{datetime.datetime.now(datetime.UTC):%Y-%m-%d}-{sha[:12]}.done"


def git(*args: str, cwd: Path = REPO, check: bool = True) -> str:
    res = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, check=check)  # noqa: S603,S607
    return res.stdout.strip()


def own_crucible(root: Path) -> Path:
    """This job's own language-crucible checkout, cloned from the primary one the first time, then synced to the pin."""
    dest = root / "family-sweep-nightly" / "language-crucible"
    if not (dest / ".git").exists():
        primary = Path(os.environ.get("FAMILY_SWEEP_CRUCIBLE_SOURCE", REPO.parent / "language-crucible"))
        dest.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(["git", "clone", "-q", str(primary), str(dest)], check=True)  # noqa: S603,S607
    env = {**os.environ, "LANGUAGE_CRUCIBLE_PATH": str(dest)}
    subprocess.run([sys.executable, str(TOOLS / "crucible_pins.py"), "sync", "language"], check=True, env=env)  # noqa: S603
    return dest


def run(args: argparse.Namespace) -> int:
    root = equivalence_env.scratch_root(args.root)
    verdict = census_nightly.box_verdict()
    if verdict != "GREEN" and not args.force:
        print(f"skipped: box_status says {verdict}, the sweep needs GREEN")
        return 0
    git("fetch", "-q", "origin", "main")
    sha = git("rev-parse", "origin/main")
    stamp = stamp_file(root, sha)
    if stamp.is_file() and not args.force:
        print(f"skipped: {sha[:12]} was already swept today ({stamp.name})")
        return 0
    git("checkout", "-q", "--detach", "-f", "origin/main")
    old = json.loads((REPO / BASELINE).read_text(encoding="utf-8"))
    crucible = own_crucible(root)
    venv_bin = os.environ.get("FAMILY_SWEEP_VENV_BIN")
    env = {**os.environ, "LANGUAGE_CRUCIBLE_PATH": str(crucible), "PYTHONPATH": str(REPO)}
    if venv_bin:
        env["PATH"] = f"{venv_bin}:{env['PATH']}"
    sweep = [sys.executable, str(TOOLS / "family_oracle_sweep.py"), "--write"]
    subprocess.run(["bash", str(TOOLS / "box" / "heavy-run.sh"), *sweep], check=True, env=env, cwd=REPO)  # noqa: S603,S607
    subprocess.run([sys.executable, str(TOOLS / "family_validity_chart.py")], check=True, env=env, cwd=REPO)  # noqa: S603
    new = json.loads((REPO / BASELINE).read_text(encoding="utf-8"))
    dirty = git("status", "--porcelain", "--", BASELINE, *CHART_FILES)
    if not dirty:
        print("no change: the baseline and the grid are what main already has")
    else:
        before, after = len(family_red_cells.red_cells(old)), len(family_red_cells.red_cells(new))
        changes = diff_cells(old, new)
        slices = [
            family_red_cells.slice_line(lang, cs)
            for lang, cs in family_red_cells.by_language(family_red_cells.red_cells(new)).items()
        ]
        body = pr_body(sha, before, after, changes, slices)
        print(
            f"red cells {before} -> {after}; regressed {len(changes['regressed'])}, improved {len(changes['improved'])}"
        )
        if args.dry_run:
            print(body)
        else:
            publish(sha, body)
    if not args.dry_run:
        stamp.parent.mkdir(parents=True, exist_ok=True)
        stamp.write_text(f"{sha}\n", encoding="utf-8")
    git("checkout", "-q", "--detach", "-f", "origin/main")  # leave the worktree clean for tomorrow
    return 0


def publish(sha: str, body: str) -> None:
    """Commit the swept files on the standing bot branch (fast-forward only: no force push), then open or refresh its one draft PR."""
    files = (BASELINE, *CHART_FILES)
    kept = {f: (REPO / f).read_bytes() for f in files}  # the sweep's output, carried across the branch switch
    git("checkout", "-q", "-f", "--detach", "origin/main")
    remote = git("ls-remote", "--heads", "origin", BRANCH)
    if remote:
        git("fetch", "-q", "origin", BRANCH)
        git("switch", "-q", "-C", BRANCH, f"origin/{BRANCH}")
        git(
            "merge", "-q", "--no-edit", "-X", "theirs", "origin/main"
        )  # these files are regenerated below, so main's side may win
    else:
        git("switch", "-q", "-C", BRANCH, "origin/main")
    for f, data in kept.items():
        (REPO / f).write_bytes(data)
    git("add", *files)
    if git("status", "--porcelain", "--", *files):
        git("commit", "-q", "-m", f"Refresh the family-validity baseline and grid at {sha[:12]} (Part of #8863)")
    git("push", "-q", "-u", "origin", BRANCH)
    found = subprocess.run(  # noqa: S603
        [GH, "pr", "list", "--head", BRANCH, "--state", "open", "--json", "number", "-q", ".[0].number"],
        cwd=REPO,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    if found:
        subprocess.run(["gh", "pr", "edit", found, "--body", body], cwd=REPO, check=True)  # noqa: S603,S607
        print(f"updated PR #{found}")
    else:
        out = subprocess.run(  # noqa: S603
            [
                GH,
                "pr",
                "create",
                "--draft",
                "--base",
                "main",
                "--head",
                BRANCH,
                "--title",
                "Refresh the family-validity baseline and grid (nightly, Part of #8863)",
                "--body",
                body,
            ],
            cwd=REPO,
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
        print(f"opened {out}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--dry-run", action="store_true", help="sweep and print the PR body; push, open and stamp nothing")
    ap.add_argument("--force", action="store_true", help="ignore the box verdict and the stamp")
    ap.add_argument("--root", type=Path, help="the shared scratch root (default: $GG_SCRATCH, else _shared-scratch)")
    return run(ap.parse_args(argv))


if __name__ == "__main__":
    sys.exit(main())
